-- Sistema de Análise Bloons TD 6
-- criação das tabelas (gerado a partir de modelagem.dbml)

-- ENUMS

CREATE TYPE categoria_torre AS ENUM ('primaria', 'militar', 'magia', 'suporte');

CREATE TYPE caminho_upgrade AS ENUM (
  'caminho_1', -- Superior / Top
  'caminho_2', -- Meio / Middle
  'caminho_3' -- Inferior / Bottom
);

CREATE TYPE dificuldade AS ENUM ('facil', 'medio', 'dificil', 'impopivel');

CREATE TYPE modo_jogo AS ENUM (
  'padrao',
  'alternate_bloons_rounds',
  'reverso',
  'apopalypse',
  'deflation',
  'half_cash',
  'impopivel_chimps',
  'sandbox'
);

CREATE TYPE resultado_partida AS ENUM ('vitoria', 'derrota', 'abandonada');

CREATE TYPE dificuldade_mapa AS ENUM ('iniciante', 'intermediario', 'avancado', 'especialista');

CREATE TYPE tipo_bloon AS ENUM ('normal', 'moab_class', 'especial');

-- DADOS DE REFERÊNCIA

CREATE TABLE torres (
  id                int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome              varchar(60)      NOT NULL UNIQUE,
  categoria         categoria_torre  NOT NULL,
  custo_base        int              NOT NULL, -- custo na dificuldade Médio
  tamanho_footprint varchar(20), -- circular 6, retangular 28x18
  alcance_base      decimal(6,2),
  aquatica          boolean          NOT NULL DEFAULT false,
  ativo             boolean          NOT NULL DEFAULT true
);
COMMENT ON TABLE torres IS 'Torres do jogo, categoria e custo base.';

CREATE TABLE upgrades (
  id        int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  torre_id  int             NOT NULL REFERENCES torres(id),
  caminho   caminho_upgrade NOT NULL,
  nivel     smallint        NOT NULL, -- 1 a 5
  nome      varchar(80)     NOT NULL,
  custo     int             NOT NULL, -- custo na dificuldade Médio
  descricao text
);
CREATE UNIQUE INDEX upgrades_torre_caminho_nivel_uq
ON upgrades (torre_id, caminho, nivel);
COMMENT ON TABLE upgrades IS 'Upgrades de cada torre, por caminho e nível, com custo.';

CREATE TABLE herois (
  id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome       varchar(60) NOT NULL UNIQUE,
  custo_base int         NOT NULL
);
COMMENT ON TABLE herois IS 'Heróis, pois influenciam fortemente as estratégias.';

CREATE TABLE bloons (
  id                 int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome               varchar(60) NOT NULL UNIQUE,
  tipo               tipo_bloon  NOT NULL,
  vida               int         NOT NULL,
  velocidade         decimal(6,2),
  camuflado_possivel boolean     NOT NULL DEFAULT true,
  regenera_possivel  boolean     NOT NULL DEFAULT true,
  resistencia        varchar(120), -- ex: imune a explosivos, imune a gelo
  filhos_gerados     int DEFAULT 0
);
COMMENT ON TABLE bloons IS 'Tipos de bloons e suas propriedades.';

CREATE TABLE mapas (
  id                       int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome                     varchar(60)      NOT NULL UNIQUE,
  dificuldade              dificuldade_mapa NOT NULL,
  tem_agua                 boolean          NOT NULL DEFAULT false,
  numero_caminhos          smallint         NOT NULL DEFAULT 1,
  area_util_colocacao      varchar(20), -- baixa, media, alta
  linha_de_visao_bloqueada boolean          NOT NULL DEFAULT false,
  observacoes              text
);
COMMENT ON TABLE mapas IS 'Mapas e suas características.';

-- DADOS ANALÍTICOS: ESTRATÉGIAS

CREATE TABLE estrategias (
  id                   int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome                 varchar(100) NOT NULL UNIQUE,
  descricao            text,
  autor                varchar(80),
  heroi_id             int REFERENCES herois(id), -- herói recomendado (opcional)
  dificuldade_alvo     dificuldade,
  modo_alvo            modo_jogo DEFAULT 'padrao',
  round_alvo           smallint, -- round final que a estratégia se propõe a atingir
  custo_total_estimado int, -- calculado a partir dos itens
  criada_em            timestamptz NOT NULL DEFAULT now()
);
COMMENT ON TABLE estrategias IS 'Estratégias cadastradas.';

CREATE TABLE estrategia_torres (
  id                  int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estrategia_id       int       NOT NULL REFERENCES estrategias(id) ON DELETE CASCADE,
  torre_id            int       NOT NULL REFERENCES torres(id),
  quantidade          smallint  NOT NULL DEFAULT 1,
  upgrade_caminho_1   smallint  NOT NULL DEFAULT 0, -- nível 0 a 5
  upgrade_caminho_2   smallint  NOT NULL DEFAULT 0, -- nível 0 a 5
  upgrade_caminho_3   smallint  NOT NULL DEFAULT 0, -- nível 0 a 5
  round_colocacao     smallint, -- round em que entra na estratégia
  ordem               smallint, -- ordem de colocação
  observacao          varchar(200)
);
CREATE INDEX estrategia_torres_estrategia_idx
ON estrategia_torres (estrategia_id);
CREATE INDEX estrategia_torres_torre_idx
ON estrategia_torres (torre_id);
COMMENT ON TABLE estrategia_torres IS
  'Torres e níveis de upgrade de cada estratégia. Regra do jogo (máx. 5 no caminho principal e 2 no secundário) a validar via CHECK/trigger.';

-- DADOS ANALÍTICOS: PARTIDAS

CREATE TABLE partidas (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mapa_id          int               NOT NULL REFERENCES mapas(id),
  estrategia_id    int               NOT NULL REFERENCES estrategias(id),
  dificuldade      dificuldade       NOT NULL,
  modo             modo_jogo         NOT NULL DEFAULT 'padrao',
  resultado        resultado_partida NOT NULL,
  round_final      smallint          NOT NULL, -- round em que a partida terminou
  round_inicial    smallint          NOT NULL DEFAULT 1,
  vidas_restantes  int,
  dinheiro_final   int,
  duracao_segundos int,
  jogador          varchar(80),
  jogada_em        timestamptz       NOT NULL DEFAULT now(),
  observacoes      text
);
CREATE INDEX partidas_mapa_dificuldade_idx
ON partidas (mapa_id, dificuldade);
CREATE INDEX partidas_estrategia_idx
ON partidas (estrategia_id);
CREATE INDEX partidas_resultado_idx
ON partidas (resultado);
CREATE INDEX partidas_round_final_idx
ON partidas (round_final);
COMMENT ON TABLE partidas IS 'Partidas jogadas, com mapa, dificuldade, estratégia usada e resultado.';

CREATE TABLE partida_falhas (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partida_id        bigint   NOT NULL REFERENCES partidas(id) ON DELETE CASCADE,
  round_falha       smallint NOT NULL,
  bloon_causador_id int      REFERENCES bloons(id), -- bloon que furou a defesa
  vidas_perdidas    int,
  motivo            varchar(200) -- ex: camuflado sem detecção, MOAB sem dano suficiente
);
CREATE INDEX partida_falhas_round_idx
ON partida_falhas (round_falha);
CREATE INDEX partida_falhas_bloon_idx
ON partida_falhas (bloon_causador_id);
COMMENT ON TABLE partida_falhas IS
  'Onde e por que a estratégia falhou. Base para: em qual round as estratégias costumam falhar?';

-- RECOMENDAÇÃO (materializada)

CREATE TABLE recomendacoes (
  id                  int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mapa_id             int         NOT NULL REFERENCES mapas(id),
  dificuldade         dificuldade NOT NULL,
  modo                modo_jogo   NOT NULL DEFAULT 'padrao',
  estrategia_id       int         NOT NULL REFERENCES estrategias(id),
  posicao_ranking     smallint    NOT NULL,
  taxa_vitoria        decimal(5,2) NOT NULL,
  total_partidas      int         NOT NULL,
  round_medio_derrota decimal(6,2),
  custo_beneficio     decimal(10,4), -- ex: rounds alcançados por 1.000 de custo
  calculado_em        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX recomendacoes_ranking_idx
ON recomendacoes (mapa_id, dificuldade, modo, posicao_ranking);
COMMENT ON TABLE recomendacoes IS
  'Ranking pré-calculado por mapa/dificuldade/modo. Reconstruído periodicamente a partir de partidas.';